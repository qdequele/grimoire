// Generates supabase/seed.sql: every original story in stories/ becomes a marketplace story.
// Run with `pnpm db:seed-gen` after adding or editing a story in stories/.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'stories'
const stories = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => JSON.parse(readFileSync(join(dir, d.name, 'story.json'), 'utf8')))

const QUOTE = '$story$'
for (const s of stories) {
  if (s.meta?.license === 'private') throw new Error(`${s.meta.id} is private and can't be seeded`)
  if (JSON.stringify(s).includes(QUOTE)) throw new Error(`${s.meta.id} contains ${QUOTE}`)
}

const values = stories
  .map((s) => `  ('marketplace', ${QUOTE}${JSON.stringify(s)}${QUOTE}::jsonb, now())`)
  .join(',\n')

writeFileSync(
  'supabase/seed.sql',
  '-- Generated by scripts/gen-seed.mjs from stories/. Do not edit by hand.\n' +
    `insert into public.stories (visibility, content, published_at) values\n${values};\n`,
)
console.log(`seed.sql: ${stories.length} marketplace stor${stories.length === 1 ? 'y' : 'ies'}`)
