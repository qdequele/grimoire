// Generates supabase/seed.sql: every original story in stories/ becomes a marketplace story.
// Run with `pnpm db:seed-gen` after adding or editing a story in stories/.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'stories'
const stories = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => JSON.parse(readFileSync(join(dir, d.name, 'story.json'), 'utf8')))

const QUOTE = '$story$'
for (const s of stories) {
  if (s.meta?.license === 'private') throw new Error(`${s.meta.id} is private and can't be seeded`)
  if (!/^[a-z0-9-]+$/.test(s.meta?.id ?? '')) throw new Error(`${s.meta?.id}: meta.id must be lowercase letters, digits and dashes`)
  if (JSON.stringify(s).includes(QUOTE)) throw new Error(`${s.meta.id} contains ${QUOTE}`)
}

// One insert per story, skipped when a marketplace story with the same meta.id exists (a migration may
// have added it already, e.g. 20261107120000_marketplace_dame.sql for the hosted library).
const inserts = stories
  .map(
    (s) =>
      `insert into public.stories (visibility, content, published_at)\n` +
      `select 'marketplace', ${QUOTE}${JSON.stringify(s)}${QUOTE}::jsonb, now()\n` +
      `where not exists (select 1 from public.stories where visibility = 'marketplace' and content #>> '{meta,id}' = '${s.meta.id}');`,
  )
  .join('\n\n')

writeFileSync('supabase/seed.sql', '-- Generated by scripts/gen-seed.mjs from stories/. Do not edit by hand.\n' + inserts + '\n')
console.log(`seed.sql: ${stories.length} marketplace stor${stories.length === 1 ? 'y' : 'ies'}`)
